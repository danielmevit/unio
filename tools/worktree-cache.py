SCHEMA_VERSION = 1
MAX_WORKTREES = 1024
MAX_CANDIDATES = 4096
MAX_ENTRIES = 100000
MAX_SECONDS = 30.0
MAX_DEPTH = 64
MAX_GIT_OUTPUT = 16 * 1024 * 1024
MAX_GIT_CALL_SECONDS = 10.0
MAX_RESULTS = 256
MAX_RESULT_BYTES = 1024 * 1024
MAX_SLOT_FILES = 1024
MAX_SLOT_GROUPS = 64
MAX_CLONE_PROBE = 256
MAX_MOUNTINFO = 4 * 1024 * 1024
# Keep part of the budget so every candidate can be rechecked before output.
SCAN_SHARE = 0.85

LABEL = re.compile(r'[A-Za-z0-9][A-Za-z0-9._-]{0,127}\Z')
TASK = re.compile(r'[A-Za-z0-9][A-Za-z0-9._-]{0,159}\Z')
PROJECT_PATHSPECS = tuple(':(glob)' + depth + '*.' + kind
                          for depth in ('', '*/') for kind in ('csproj', 'fsproj', 'vbproj'))
KINDS = ('bin', 'obj')
GIT_OPTIONS = ('-c', 'core.fsmonitor=false', '-c', 'core.hooksPath=/dev/null',
               '-c', 'core.untrackedCache=false')
TERMINAL_PROCESS_STATES = frozenset(('succeeded', 'failed', 'not_run'))
GIT_BUSY = ('index.lock', 'HEAD.lock', 'MERGE_HEAD', 'CHERRY_PICK_HEAD', 'REVERT_HEAD',
            'BISECT_LOG', 'rebase-merge', 'rebase-apply')
# Never scanned into. Case-insensitive; refusal keeps the whole candidate.
PROTECTED_NAMES = frozenset(('_bench', 'benchmarks', 'benchmarkdotnet.artifacts', 'reports',
                             'coord', '.git', '.unio-worker', 'credentials', 'private',
                             'artifacts', '.env', 'id_rsa', 'id_ed25519'))
PROTECTED_SUFFIXES = ('.vhdx', '.vhd', '.pem', '.key', '.pfx', '.p12')
DIR_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK
FILE_FLAGS = os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC | os.O_NONBLOCK
OBSERVATION = ('Sizes describe probable generated bytes, not reclaimable capacity. Inactive means no '
               'native activity was observed; unmanaged writers are not proven absent and this is '
               'not deletion permission.')


class UnsafeWorkspace(Exception):
    """The selected project cannot be inventoried; exit 2."""


class Exhausted(Exception):
    """A declared bound ran out; `reason` names it."""

    def __init__(self, reason):
        super().__init__(reason)
        self.reason = reason


class Refused(Exception):
    """Evidence that a candidate must not be presented."""

    def __init__(self, reason):
        super().__init__(reason)
        self.reason = reason


class Unreadable(Exception):
    """Metadata could not be observed; its size stays Unknown."""


class Limits:
    def __init__(self, worktrees=MAX_WORKTREES, candidates=MAX_CANDIDATES,
                 entries=MAX_ENTRIES, seconds=MAX_SECONDS):
        self.worktrees = worktrees
        self.candidates = candidates
        self.entries = entries
        self.seconds = seconds


class Budget:
    def __init__(self, limits, clock=time.monotonic):
        self.clock = clock
        start = clock()
        self.scan_deadline = start + limits.seconds * SCAN_SHARE
        self.hard_deadline = start + limits.seconds
        self.entries = limits.entries

    def tick(self):
        if self.clock() >= self.scan_deadline:
            raise Exhausted('time_limit')

    def entry(self):
        self.tick()
        if self.entries <= 0:
            raise Exhausted('entry_limit')
        self.entries -= 1


def noop_hook(_event, _detail):
    return None


# ------------------------------------------------------------------- git
def git_env():
    env = {'PATH': os.environ.get('PATH', '/usr/bin:/bin'), 'LC_ALL': 'C',
           'GIT_OPTIONAL_LOCKS': '0', 'GIT_TERMINAL_PROMPT': '0', 'GIT_NO_REPLACE_OBJECTS': '1',
           'GIT_CONFIG_NOSYSTEM': '1', 'GIT_CONFIG_GLOBAL': '/dev/null', 'GIT_NO_LAZY_FETCH': '1',
           'HOME': '/nonexistent'}
    return env


def git(cwd, budget, *args):
    """Run one bounded nonmutating Git read; return bytes or raise."""
    budget.tick()
    limit = min(MAX_GIT_CALL_SECONDS, budget.scan_deadline - budget.clock())
    end = budget.clock() + max(limit, 0)
    try:
        child = subprocess.Popen(('git', '-C', cwd) + GIT_OPTIONS + args, stdin=subprocess.DEVNULL,
                                 stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, env=git_env(),
                                 close_fds=True, start_new_session=True)
    except OSError as error:
        raise Unreadable('git unavailable') from error
    output = []
    size = 0
    try:
        while True:
            remaining = end - budget.clock()
            if remaining <= 0:
                raise Exhausted('time_limit')
            ready = select.select([child.stdout], [], [], min(remaining, 0.25))[0]
            if not ready:
                continue
            chunk = os.read(child.stdout.fileno(), 65536)
            if not chunk:
                break
            size += len(chunk)
            if size > MAX_GIT_OUTPUT:
                raise Exhausted('git_output_limit')
            output.append(chunk)
        while child.poll() is None:
            if budget.clock() >= end:
                raise Exhausted('time_limit')
            time.sleep(0.005)
    finally:
        if child.poll() is None:
            try:
                os.killpg(child.pid, signal.SIGKILL)
            except OSError:
                pass
        child.stdout.close()
        child.wait()
    if child.returncode != 0:
        raise Unreadable('git exit %d' % child.returncode)
    return b''.join(output)


def split_nul(raw):
    return [part for part in raw.split(b'\0') if part]


def registration(worktree, common):
    """Read one worktree's two-way Git registration, or return None.

    `git worktree list` costs 20s for 400 worktrees on WSL drvfs, so each worker
    is checked on its own: its .git file must name a record directly under the
    project's common Git directory, and that record's gitdir must name it back.
    """
    try:
        raw = read_regular(os.path.join(worktree, '.git'), 8192)[0]
        if not raw.startswith(b'gitdir: '):
            return None
        admin = os.path.realpath(os.path.join(worktree, os.fsdecode(raw[8:].rstrip(b'\n'))))
        if os.path.dirname(admin) != os.path.join(common, 'worktrees'):
            return None
        back = read_regular(os.path.join(admin, 'gitdir'), 8192)[0]
        head = read_regular(os.path.join(admin, 'HEAD'), 8192)[0]
        shared = read_regular(os.path.join(admin, 'commondir'), 8192)[0]
    except (OSError, Refused):
        return None
    target = os.path.join(admin, os.fsdecode(back.rstrip(b'\n')))
    if os.path.realpath(os.path.dirname(target)) != worktree or os.path.basename(target) != '.git':
        return None
    branch = head.strip()[5:].strip() if head.startswith(b'ref:') else b''
    return dict(admin=admin, branch=os.fsdecode(branch),
                common=os.path.realpath(os.path.join(admin, os.fsdecode(shared.rstrip(b'\n')))),
                locked=os.path.lexists(os.path.join(admin, 'locked')))


def find_clone(root, budget):
    """Exactly one direct child must be a main clone that owns linked worktrees."""
    found = []
    probed = 0
    with os.scandir(root) as entries:
        for entry in entries:
            probed += 1
            if probed > MAX_CLONE_PROBE:
                raise UnsafeWorkspace('too many project entries to identify the main clone')
            if entry.name in ('coord', 'wt') or entry.is_symlink():
                continue
            try:
                info = os.lstat(os.path.join(entry.path, '.git'))
                links = os.lstat(os.path.join(entry.path, '.git', 'worktrees'))
            except OSError:
                continue
            if stat.S_ISDIR(info.st_mode) and stat.S_ISDIR(links.st_mode):
                found.append(entry.path)
    budget.tick()
    if len(found) != 1:
        raise UnsafeWorkspace('expected one main clone with linked worktrees; found %d' % len(found))
    return found[0]


# ---------------------------------------------------- bounded observations
def read_regular(path, limit):
    """Read a small regular single-link control file; refuse other shapes."""
    fd = os.open(path, FILE_FLAGS)
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1 or info.st_size > limit:
            raise Refused('unsafe_control_file')
        raw = os.read(fd, limit + 1)
        if len(raw) > limit:
            raise Refused('unsafe_control_file')
        return raw, (info.st_ino, info.st_size, info.st_mtime_ns)
    finally:
        os.close(fd)


def probe_lock(path):
    """Return held/free/missing/unknown without creating or writing anything.

    The probe holds a nonblocking flock for an instant, as native status does;
    a simultaneous `flock -n` starter could observe that instant as busy.
    """
    try:
        fd = os.open(path, FILE_FLAGS)
    except FileNotFoundError:
        return 'missing', None
    except OSError:
        return 'unknown', None
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode):
            return 'unknown', None
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as error:
            if error.errno in (errno.EWOULDBLOCK, errno.EACCES):
                return 'held', info.st_ino
            return 'unknown', info.st_ino
        return 'free', info.st_ino
    finally:
        os.close(fd)


def worker_slots(root):
    """Return (workers with a work-policy slot, whether all slots were understood)."""
    base = os.path.join(root, 'coord', '.locks', 'work-policy-slots')
    workers, known, files = set(), True, 0
    try:
        groups = sorted(os.listdir(base))
    except FileNotFoundError:
        return workers, True
    except OSError:
        return workers, False
    if len(groups) > MAX_SLOT_GROUPS:
        return workers, False
    for group in groups:
        directory = os.path.join(base, group)
        try:
            if stat.S_ISLNK(os.lstat(directory).st_mode):
                known = False
                continue
            names = sorted(os.listdir(directory))
        except OSError:
            known = False
            continue
        for name in names:
            if not name.endswith('.json'):
                continue
            files += 1
            if files > MAX_SLOT_FILES:
                return workers, False
            try:
                value = json.loads(read_regular(os.path.join(directory, name), 65536)[0])
                workers.add(value['worker'])
            except FileNotFoundError:
                continue
            except (OSError, Refused, ValueError, KeyError, TypeError):
                known = False
    return workers, known


def activity(root, worker):
    """Observe native activity; return (blocking reason or None, fingerprint)."""
    locks = os.path.join(root, 'coord', '.locks')
    state, lock_inode = probe_lock(os.path.join(locks, worker + '.lock'))
    if state == 'held':
        return 'active_lock', None
    if state == 'unknown':
        return 'activity_unknown_lock', None
    if state == 'missing':
        return 'activity_unknown_no_lock', None
    if os.path.lexists(os.path.join(locks, 'codex-worker-' + worker + '.json')):
        return 'native_session_manifest', None
    slots, known = worker_slots(root)
    if worker in slots:
        return 'work_policy_slot', None
    if not known:
        return 'activity_unknown_slots', None
    directory = os.path.join(root, 'coord', 'results', worker)
    try:
        if not stat.S_ISDIR(os.lstat(directory).st_mode):
            return 'activity_unknown_results', None
        names = sorted(name for name in os.listdir(directory) if name.endswith('.json'))
    except FileNotFoundError:
        return 'activity_unknown_no_result', None
    except OSError:
        return 'activity_unknown_results', None
    if not names:
        return 'activity_unknown_no_result', None
    if len(names) > MAX_RESULTS:
        return 'activity_unknown_result_limit', None
    fingerprint = [lock_inode]
    for name in names:
        try:
            raw, facts = read_regular(os.path.join(directory, name), MAX_RESULT_BYTES)
            document = json.loads(raw)
            process_state = document['process']['state']
            sections = [document.get(key) for key in ('validation', 'review')]
        except (OSError, Refused, ValueError, KeyError, TypeError):
            return 'activity_unknown_results', None
        if process_state == 'running':
            return 'running_orphan_uncertain', None
        if process_state not in TERMINAL_PROCESS_STATES:
            return 'activity_unknown_results', None
        if any(isinstance(item, dict) and item.get('state') == 'running' for item in sections):
            return 'running_orphan_uncertain', None
        task = name[:-5]
        if TASK.match(task):
            owner, _ = probe_lock(os.path.join(locks, '.owners', task + '.lock'))
            if owner == 'held':
                return 'active_task_owner', None
            if owner == 'unknown':
                return 'activity_unknown_owner', None
        fingerprint.append((name, facts))
    return None, tuple(fingerprint)


def mount_points():
    """Return physical mount points, or None when the table cannot be observed."""
    try:
        with open('/proc/self/mountinfo', 'rb') as stream:
            raw = stream.read(MAX_MOUNTINFO + 1)
    except OSError:
        return None
    if len(raw) > MAX_MOUNTINFO:
        return None
    points = set()
    for line in raw.split(b'\n'):
        fields = line.split(b' ')
        if len(fields) > 4:
            decoded = re.sub(rb'\\([0-7]{3})', lambda m: bytes((int(m.group(1), 8),)), fields[4])
            points.add(os.fsdecode(decoded))
    return points


def mount_inside(points, path):
    if points is None:
        return True
    prefix = path.rstrip('/') + '/'
    return any(point == path or point.startswith(prefix) for point in points)


# ------------------------------------------------------- no-follow traversal
def protected(name):
    lowered = name.lower()
    return lowered in PROTECTED_NAMES or lowered.endswith(PROTECTED_SUFFIXES)


def walk(fd, relative, device, depth, budget, totals, digest):
    if depth > MAX_DEPTH:
        raise Refused('depth_limit')
    records = []
    try:
        with os.scandir(fd) as entries:
            for entry in entries:
                budget.entry()
                name = entry.name
                if protected(name):
                    raise Refused('protected_entry')
                try:
                    info = entry.stat(follow_symlinks=False)
                except FileNotFoundError:
                    raise Refused('changing_entries') from None
                except OSError as error:
                    raise Unreadable('metadata') from error
                records.append((name, info))
    except FileNotFoundError:
        raise Refused('changing_entries') from None
    except OSError as error:
        raise Unreadable('directory') from error
    records.sort(key=lambda item: os.fsencode(item[0]))
    for name, info in records:
        path = relative + '/' + name
        mode = info.st_mode
        if stat.S_ISLNK(mode):
            raise Refused('symlink')
        if info.st_dev != device:
            raise Refused('mount_escape')
        digest.update(repr((path, mode, info.st_ino, info.st_size, info.st_mtime_ns,
                            info.st_ctime_ns, info.st_nlink if stat.S_ISREG(mode) else 0)).encode(
                                'utf-8', 'surrogateescape'))
        if stat.S_ISREG(mode):
            if info.st_nlink != 1:
                raise Refused('hardlink')
            totals['logical'] += info.st_size
            if info.st_size and not info.st_blocks:
                totals['allocated_known'] = False
            totals['allocated'] += info.st_blocks * 512
        elif stat.S_ISDIR(mode):
            child = open_child(fd, name, info)
            try:
                walk(child, path, device, depth + 1, budget, totals, digest)
            finally:
                os.close(child)
        else:
            raise Refused('unsupported_file_type')


def open_child(parent, name, expected):
    try:
        child = os.open(name, DIR_FLAGS, dir_fd=parent)
    except (FileNotFoundError, NotADirectoryError):
        raise Refused('changing_entries') from None
    except OSError as error:
        if error.errno == errno.ELOOP:
            raise Refused('symlink') from None
        raise Unreadable('directory') from error
    info = os.fstat(child)
    if (info.st_ino, info.st_dev) != (expected.st_ino, expected.st_dev):
        os.close(child)
        raise Refused('changing_entries')
    return child


class VerifyBudget:
    """The second observation may revisit only what the first one counted."""

    def __init__(self, budget, entries):
        self.budget = budget
        self.entries = entries

    def entry(self):
        self.budget.tick()
        if self.entries <= 0:
            raise Refused('changing_entries')
        self.entries -= 1


def measure(parent_fd, name, device, budget, hook, label):
    """Observe one cache twice; a difference between observations refuses it."""
    try:
        info = os.stat(name, dir_fd=parent_fd, follow_symlinks=False)
    except FileNotFoundError:
        return None
    if stat.S_ISLNK(info.st_mode):
        raise Refused('symlink')
    if not stat.S_ISDIR(info.st_mode):
        raise Refused('unsupported_file_type')
    if info.st_dev != device:
        raise Refused('mount_escape')
    fd = open_child(parent_fd, name, info)
    totals = dict(logical=0, allocated=0, allocated_known=True)
    first = hashlib.sha256()
    before = budget.entries
    try:
        try:
            walk(fd, name, device, 0, budget, totals, first)
        except (Exhausted, Unreadable) as error:
            error.partial_logical = totals['logical']
            raise
        hook('between_passes', label)
        again = dict(logical=0, allocated=0, allocated_known=True)
        second = hashlib.sha256()
        try:
            walk(fd, name, device, 0, VerifyBudget(budget, before - budget.entries), again, second)
        except (Exhausted, Unreadable) as error:
            error.partial_logical = totals['logical']
            raise
        if first.digest() != second.digest():
            raise Refused('changing_entries')
    finally:
        os.close(fd)
    return totals, (info.st_ino, info.st_dev)


# -------------------------------------------------------------- worktrees
def validate_worker(root, worker, common):
    """Return (physical worktree, Git record, None) or (None, None, excluded reason)."""
    path = os.path.join(root, 'wt', worker)
    if not LABEL.match(worker):
        return None, None, 'invalid_worker_name'
    try:
        info = os.lstat(path)
        if not stat.S_ISDIR(info.st_mode):
            return None, None, 'not_a_worktree_directory'
        if info.st_uid != os.getuid():
            return None, None, 'foreign_owner'
        git_file = os.lstat(os.path.join(path, '.git'))
    except FileNotFoundError:
        return None, None, 'not_a_worktree'
    except OSError:
        return None, None, 'worktree_unreadable'
    if not stat.S_ISREG(git_file.st_mode):
        return None, None, 'not_a_linked_worktree'
    try:
        marker = read_regular(os.path.join(path, '.unio-worker'), 4096)[0]
    except (OSError, Refused):
        return None, None, 'worker_marker_missing_or_unsafe'
    if marker.decode('utf-8', 'replace').strip() != worker:
        return None, None, 'worker_marker_mismatch'
    physical = os.path.realpath(path)
    record = registration(physical, common)
    if record is None:
        return None, None, 'unregistered_worktree'
    if record['locked']:
        return None, None, 'git_worktree_locked'
    if record['branch'] != 'refs/heads/agent/' + worker:
        return None, None, 'worker_branch_mismatch'
    return physical, record, None


def git_identity(record, common):
    """Require the project's common Git directory and no Git operation in flight."""
    if record['common'] != common:
        return 'foreign_git_directory'
    for name in GIT_BUSY:
        if os.path.lexists(os.path.join(record['admin'], name)):
            return 'git_operation_in_progress'
    return None


def tracked_projects(worktree, budget):
    """Return (project directories, unsafe-record reason) from the worker index."""
    raw = git(worktree, budget, 'ls-files', '-z', '--stage', '--', *PROJECT_PATHSPECS)
    projects = set()
    for record in split_nul(raw):
        meta, _, name = record.partition(b'\t')
        fields = meta.split(b' ')
        if len(fields) != 3 or fields[2] != b'0' or fields[0] not in (b'100644', b'100755'):
            return set(), 'ambiguous_project_index_entry'
        parts = os.fsdecode(name).split('/')
        if len(parts) > 2:
            return set(), 'ambiguous_project_index_entry'
        projects.add('' if len(parts) == 1 else parts[0])
    return projects, None


def project_file_present(worktree, project, budget):
    """A candidate project must still hold a regular tracked project file."""
    raw = git(worktree, budget, 'ls-files', '-z', '--', *(spec for spec in PROJECT_PATHSPECS
                                                          if spec.count('/') == (1 if project else 0)))
    for name in split_nul(raw):
        text = os.fsdecode(name)
        if (project and text.startswith(project + '/')) or (not project and '/' not in text):
            try:
                if stat.S_ISREG(os.lstat(os.path.join(worktree, text)).st_mode):
                    return True
            except OSError:
                continue
    return False


def scan_worker(root, worker, worktree, budget, limits, report, points, hook):
    relative = 'wt/' + worker
    projects, unsafe = tracked_projects(worktree, budget)
    if unsafe:
        report.exclude(relative, worker, unsafe)
        return
    wanted = []
    for project in sorted(projects):
        for kind in KINDS:
            wanted.append((project, kind))
    fd = os.open(worktree, DIR_FLAGS)
    try:
        device = os.fstat(fd).st_dev
        for project, kind in wanted:
            budget.tick()
            label = (relative + '/' + project if project else relative) + '/' + kind
            cache = cache_path(worktree, project, kind)
            if not os.path.lexists(cache):
                continue
            if project and (protected(project) or project in KINDS):
                report.exclude(label, worker, 'protected_project_directory')
                continue
            if report.seen_candidates >= limits.candidates:
                report.exclude(label, worker, 'candidate_limit')
                report.mark_partial('candidate_limit')
                continue
            parent = fd
            try:
                if project:
                    try:
                        project_info = os.stat(project, dir_fd=fd, follow_symlinks=False)
                    except FileNotFoundError:
                        continue
                    if stat.S_ISLNK(project_info.st_mode):
                        raise Refused('symlink')
                    if not stat.S_ISDIR(project_info.st_mode):
                        raise Refused('unsupported_file_type')
                    if project_info.st_dev != device:
                        raise Refused('mount_escape')
                    parent = open_child(fd, project, project_info)
                try:
                    report.seen_candidates += 1
                    if not project_file_present(worktree, project, budget):
                        raise Refused('project_file_not_regular')
                    if mount_inside(points, cache):
                        raise Refused('mount_escape' if points is not None else 'mount_table_unknown')
                    if git(worktree, budget, '--literal-pathspecs', 'ls-files', '-z', '--',
                           (project + '/' + kind) if project else kind):
                        raise Refused('tracked_files')
                    measured = measure(parent, kind, device, budget, hook, label)
                    if measured is None:
                        continue
                    totals, identity = measured
                    report.candidate(label, worker, kind, totals, identity, cache)
                finally:
                    if parent != fd:
                        os.close(parent)
            except Refused as refusal:
                report.exclude(label, worker, refusal.reason)
            except Unreadable as error:
                report.partial_candidate(label, worker, kind, 'read_error', error, cache)
                report.mark_partial('read_error')
            except Exhausted as error:
                report.mark_partial(error.reason)
                if hasattr(error, 'partial_logical'):
                    report.partial_candidate(label, worker, kind, error.reason, error, cache)
                else:
                    report.exclude(label, worker, error.reason)
                raise
    finally:
        os.close(fd)


def cache_path(worktree, project, kind):
    return os.path.join(worktree, project, kind) if project else os.path.join(worktree, kind)


class Report:
    def __init__(self):
        self.candidates = []
        self.excluded = []
        self.partial_reasons = []
        self.seen_candidates = 0

    def mark_partial(self, reason):
        if reason not in self.partial_reasons:
            self.partial_reasons.append(reason)

    def exclude(self, path, worker, reason):
        self.excluded.append(dict(path=path, worker=worker, reason=reason))

    def candidate(self, path, worker, kind, totals, identity, physical):
        self.candidates.append(dict(
            path=path, worker=worker, kind=kind, logical_bytes=totals['logical'],
            allocated_bytes=totals['allocated'] if totals['allocated_known'] else None,
            status='inactive_observed', _identity=identity, _physical=physical))

    def partial_candidate(self, path, worker, kind, reason, error, physical):
        self.candidates.append(dict(
            path=path, worker=worker, kind=kind, logical_bytes=None, allocated_bytes=None,
            status='partial', partial_reason=reason,
            partial_observed_logical_bytes=getattr(error, 'partial_logical', None),
            _identity=None, _physical=physical))


def final_recheck(root, report, budget, hook):
    """Recheck activity and identity immediately before presenting candidates."""
    kept = []
    for item in report.candidates:
        hook('before_present', item['path'])
        if budget.clock() >= budget.hard_deadline:
            report.exclude(item['path'], item['worker'], 'activity_recheck_unavailable')
            report.mark_partial('time_limit')
            continue
        reason, fingerprint = activity(root, item['worker'])
        if reason is None and fingerprint != report.fingerprints.get(item['worker']):
            reason = 'activity_changed'
        if reason is None and item['_identity'] is not None:
            try:
                info = os.lstat(item['_physical'])
                if (info.st_ino, info.st_dev) != item['_identity'] or not stat.S_ISDIR(info.st_mode):
                    reason = 'changing_entries'
            except OSError:
                reason = 'changing_entries'
        if reason:
            report.exclude(item['path'], item['worker'], reason)
        else:
            kept.append(item)
    report.candidates = kept


def workspace_root(project):
    root = os.path.realpath(os.path.abspath(project))
    for parts in (('coord',), ('wt',), ('coord', 'results'), ('coord', '.locks')):
        path = os.path.join(root, *parts)
        try:
            info = os.lstat(path)
        except FileNotFoundError:
            if parts in (('coord',), ('wt',)):
                raise UnsafeWorkspace('no Unio workspace (coord/ and wt/) at the selected path') from None
            continue
        except OSError as error:
            raise UnsafeWorkspace('workspace unreadable: ' + '/'.join(parts)) from error
        if not stat.S_ISDIR(info.st_mode):
            raise UnsafeWorkspace('unsafe workspace directory: ' + '/'.join(parts))
    return root


def stop_observation(root):
    try:
        os.lstat(os.path.join(root, 'coord', 'STOP'))
        return True
    except FileNotFoundError:
        return False
    except OSError:
        return None


def inventory(project, limits=None, hook=noop_hook, clock=time.monotonic):
    """Build one inventory document. Raises UnsafeWorkspace for exit 2."""
    limits = limits or Limits()
    budget = Budget(limits, clock)
    root = workspace_root(project)
    report = Report()
    report.fingerprints = {}
    try:
        clone = find_clone(root, budget)
        common = os.path.realpath(os.path.join(clone, '.git'))
    except (OSError, Exhausted) as error:
        raise UnsafeWorkspace('cannot identify the main clone') from error
    names = []
    truncated = False
    try:
        with os.scandir(os.path.join(root, 'wt')) as entries:
            for entry in entries:
                if len(names) >= limits.worktrees:
                    truncated = True
                    break
                names.append(entry.name)
    except OSError as error:
        raise UnsafeWorkspace('wt directory unreadable') from error
    if truncated:
        report.mark_partial('worktree_limit')
        report.excluded.append(dict(path='wt', worker=None, reason='worktree_limit'))
    names.sort(key=os.fsencode)
    points = mount_points()
    stopped_at = None
    for index, worker in enumerate(names):
        relative = 'wt/' + worker
        try:
            budget.tick()
            worktree, record, reason = validate_worker(root, worker, common)
            if reason:
                report.exclude(relative, worker, reason)
                continue
            reason = git_identity(record, common)
            if reason:
                report.exclude(relative, worker, reason)
                continue
            reason, fingerprint = activity(root, worker)
            if reason:
                report.exclude(relative, worker, reason)
                continue
            report.fingerprints[worker] = fingerprint
            hook('worker_validated', worker)
            scan_worker(root, worker, worktree, budget, limits, report, points, hook)
        except Unreadable:
            report.exclude(relative, worker, 'git_metadata_unknown')
        except OSError:
            report.exclude(relative, worker, 'worktree_unreadable')
        except Exhausted as error:
            report.mark_partial(error.reason)
            report.exclude(relative, worker, error.reason)
            stopped_at = index + 1
            break
    if stopped_at is not None and stopped_at < len(names):
        for worker in names[stopped_at:]:
            report.exclude('wt/' + worker, worker, 'not_scanned_bound_reached')
    final_recheck(root, report, budget, hook)
    return document(root, report)


def document(root, report):
    candidates = []
    for item in sorted(report.candidates, key=lambda value: os.fsencode(value['path'])):
        candidates.append({key: value for key, value in item.items() if not key.startswith('_')})
    complete = [item for item in candidates if item['status'] == 'inactive_observed']
    known_allocated = [item['allocated_bytes'] for item in complete]
    return dict(
        schema_version=SCHEMA_VERSION,
        observed_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
        dry_run=True,
        scope='current_workspace',
        stop_active=stop_observation(root),
        partial=bool(report.partial_reasons),
        partial_reasons=report.partial_reasons,
        observation=OBSERVATION,
        totals=dict(
            logical_bytes=sum(item['logical_bytes'] for item in complete),
            allocated_bytes=None if None in known_allocated else sum(known_allocated),
            logical_bytes_complete=not report.partial_reasons
            and len(complete) == len(candidates)),
        candidates=candidates,
        excluded=report.excluded)


# ----------------------------------------------------------------- output
def printable(text):
    if text is None:
        return 'Unknown'
    return ''.join(ch if ch.isprintable() else '\\x{%x}' % ord(ch) for ch in str(text))


def size_text(value):
    if value is None:
        return 'Unknown'
    amount = float(value)
    for unit in ('B', 'KiB', 'MiB', 'GiB'):
        if amount < 1024 or unit == 'GiB':
            return ('%d B' % value) if unit == 'B' else '%.1f %s' % (amount, unit)
        amount /= 1024
    return str(value)


def human(result):
    lines = ['Build-cache inventory (dry run; nothing was changed)']
    if result['stop_active'] is None:
        lines.append('STOP: Unknown')
    else:
        lines.append('STOP: ' + ('active' if result['stop_active'] else 'clear'))
    totals = result['totals']
    lines.append('Candidates: %d; probable generated: %s logical, %s allocated%s' % (
        len(result['candidates']), size_text(totals['logical_bytes']), size_text(totals['allocated_bytes']),
        '' if totals['logical_bytes_complete'] else ' (lower bound)'))
    for item in result['candidates']:
        lines.append('  %s  [%s] %s' % (printable(item['path']), item['status'], size_text(item['logical_bytes'])))
    counts = {}
    for item in result['excluded']:
        counts[item['reason']] = counts.get(item['reason'], 0) + item.get('count', 1)
    lines.append('Excluded: %d' % sum(counts.values()))
    for reason in sorted(counts):
        lines.append('  %s: %d' % (reason, counts[reason]))
    if result['partial']:
        lines.append('PARTIAL inventory (%s); it does not establish safety or completeness.'
                     % ', '.join(result['partial_reasons']))
    lines.append(OBSERVATION)
    lines.append('Excluded paths: --json. Details: docs/BUILD-CACHE-HYGIENE.md')
    return '\n'.join(lines) + '\n'


def parser():
    build = argparse.ArgumentParser(
        prog='unio cache', allow_abbrev=False,
        description='Read-only inventory of likely generated .NET bin/obj directories in inactive '
                    'registered worker worktrees of this workspace. Never deletes; no provider calls.')
    build.add_argument('--project', metavar='PATH', help='Unio workspace (default: current workspace)')
    build.add_argument('--json', action='store_true', help='print the schema_version 1 JSON document')
    build.add_argument('--dry-run', action='store_true', help='accepted; inventory is always a dry run')
    return build


def main(argv=None):
    args = parser().parse_args(argv)
    if not args.project:
        sys.stderr.write('unio cache: no project selected; pass --project PATH\n')
        return 2
    try:
        result = inventory(args.project)
    except UnsafeWorkspace as error:
        sys.stderr.write('unio cache: ' + printable(error) + '\n')
        return 2
    try:
        if args.json:
            sys.stdout.write(json.dumps(result, indent=2, sort_keys=True) + '\n')
        else:
            sys.stdout.write(human(result))
        sys.stdout.flush()
    except BrokenPipeError:
        os.dup2(os.open(os.devnull, os.O_WRONLY), sys.stdout.fileno())
    return 0


if __name__ == '__main__':
    sys.exit(main())
